import asyncio,json
from pathlib import Path
from playwright.async_api import async_playwright
async def main():
 data=json.loads(Path('/tmp/browser/entry-assistant/session.json').read_text())
 async with async_playwright() as p:
  browser=await p.chromium.launch(headless=True)
  page=await browser.new_page(viewport={'width':1280,'height':1800})
  await page.goto('http://localhost:8080')
  await page.evaluate('s=>localStorage.setItem("sb-mijelbyriioabfwddjfj-auth-token",JSON.stringify(s))',data['session'])
  try: await page.goto('http://localhost:8080/entries?meet='+data['meet'],wait_until='networkidle')
  except Exception: await page.goto('http://localhost:8080/entries?meet='+data['meet'],wait_until='networkidle')
  await page.get_by_role('button',name='Generar sugerencias').click()
  await page.get_by_role('button',name='Guardar inscripciones',exact=True).first.click()
  await page.get_by_text('Inscripciones guardadas.',exact=True).wait_for()
  await page.get_by_role('navigation',name='Navegación principal').get_by_role('link',name='Inicio',exact=True).click()
  await page.get_by_role('heading',name='Requiere atención').wait_for()
  await page.get_by_label('Buscar atletas y competencias').first.fill('Ana Assistant')
  await page.get_by_role('link',name='Ana Assistant',exact=True).first.click()
  await page.get_by_role('heading',level=1).wait_for()
  await page.get_by_role('link',name='Inscripciones',exact=True).last.click()
  await page.get_by_role('heading',name='Asistente de inscripción').wait_for()
  await page.get_by_label('Filtro global Sexo').first.click()
  await page.get_by_role('option',name='Femenino',exact=True).click()
  await page.get_by_role('button',name='Guardar filtros',exact=True).first.click()
  await page.get_by_role('navigation',name='Navegación principal').get_by_role('link',name='Rankings',exact=True).click()
  await page.get_by_role('heading',name='Rankings',exact=True).wait_for()
  assert 'Femenino' in await page.get_by_label('Filtro global Sexo').first.inner_text()
  await page.reload(wait_until='networkidle')
  assert 'Femenino' in await page.get_by_label('Filtro global Sexo').first.inner_text()
  await page.screenshot(path='/tmp/browser/entry-assistant/navigation-desktop.png')
  await page.set_viewport_size({'width':390,'height':844})
  await page.get_by_role('button',name='Más',exact=True).click()
  await page.get_by_role('dialog').get_by_role('link',name='Inicio',exact=True).click()
  await page.get_by_role('heading',name='Requiere atención').wait_for()
  await page.screenshot(path='/tmp/browser/entry-assistant/navigation-mobile.png')
  assert not await page.evaluate('document.documentElement.scrollWidth > innerWidth')
  print('navigation search filters persistence and mobile verified')
  await browser.close()
asyncio.run(main())
